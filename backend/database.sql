SET @igv_factor = 1 + COALESCE(
    (SELECT CAST(valor AS DECIMAL(8,4)) FROM configuracion WHERE clave = 'igv'),
    18
) / 100;
UPDATE factura_detalle d
JOIN productos p ON p.id = d.producto_id
SET d.precio = ROUND(d.precio * @igv_factor, 2);
