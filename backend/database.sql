CREATE TABLE usuarios (
    id INT AUTO_INCREMENT PRIMARY KEY,
    usuario VARCHAR(40) NOT NULL UNIQUE,
    clave CHAR(64) NOT NULL,
    nombre VARCHAR(80) NOT NULL,
    rol VARCHAR(20) NOT NULL DEFAULT 'USUARIO'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE clientes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    razon_social VARCHAR(160) NOT NULL,
    ruc CHAR(11) NULL,
    codigo_sap VARCHAR(40) NULL,
    telefono VARCHAR(30) NULL,
    email VARCHAR(120) NULL,
    direccion VARCHAR(200) NULL,
    contacto_nombre VARCHAR(120) NULL,
    INDEX idx_clientes_ruc (ruc)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE productos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(500) NOT NULL,
    marca VARCHAR(80) NULL,
    presentacion VARCHAR(100) NULL,
    unidad VARCHAR(30) NULL DEFAULT 'UND',
    precio DECIMAL(14,4) NOT NULL DEFAULT 0,
    costo DECIMAL(14,4) NULL,
    es_ajuste TINYINT(1) NOT NULL DEFAULT 0,
    INDEX idx_productos_nombre (nombre)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE producto_codigos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    producto_id INT NOT NULL,
    cliente_id INT NULL,
    codigo VARCHAR(80) NOT NULL,
    tipo ENUM('sap','interno') NOT NULL DEFAULT 'interno',
    CONSTRAINT fk_producto_codigos_producto
        FOREIGN KEY (producto_id) REFERENCES productos(id),
    CONSTRAINT fk_producto_codigos_cliente
        FOREIGN KEY (cliente_id) REFERENCES clientes(id) ON DELETE CASCADE,
    UNIQUE KEY uq_producto_codigo_cliente (cliente_id, codigo),
    INDEX idx_producto_codigos_codigo (codigo),
    INDEX idx_producto_codigos_producto (producto_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE listas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    tipo ENUM('banco','forma_pago','motivo') NOT NULL,
    nombre VARCHAR(80) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE configuracion (
    clave VARCHAR(40) PRIMARY KEY,
    valor VARCHAR(200) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE pendientes_importacion (
    id INT AUTO_INCREMENT PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    anio SMALLINT NULL,
    subtotal_excel DECIMAL(16,6) NULL,
    igv_excel DECIMAL(16,6) NULL,
    total_excel DECIMAL(16,6) NULL,
    fuente VARCHAR(120) NOT NULL,
    nota VARCHAR(250) NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE facturas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    numero VARCHAR(20) NOT NULL UNIQUE,
    nro_guia VARCHAR(40) NULL,
    nro_oc VARCHAR(60) NULL,
    cliente_id INT NULL,
    emision DATE NOT NULL,
    vencimiento DATE NULL,
    subtotal DECIMAL(14,2) NOT NULL DEFAULT 0,
    igv DECIMAL(14,2) NOT NULL DEFAULT 0,
    total DECIMAL(14,2) NOT NULL DEFAULT 0,
    retencion DECIMAL(14,2) NOT NULL DEFAULT 0,
    total_neto DECIMAL(14,2) NOT NULL DEFAULT 0,
    utilidad DECIMAL(14,2) NULL,
    anulada TINYINT(1) NOT NULL DEFAULT 0,
    motivo VARCHAR(120) NULL,
    CONSTRAINT fk_facturas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes(id),
    INDEX idx_facturas_emision (emision),
    INDEX idx_facturas_cliente (cliente_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE factura_detalle (
    id INT AUTO_INCREMENT PRIMARY KEY,
    factura_id INT NOT NULL,
    producto_id INT NOT NULL,
    cantidad DECIMAL(14,3) NOT NULL,
    precio DECIMAL(14,4) NOT NULL,
    descuento DECIMAL(5,2) NOT NULL DEFAULT 0,
    total DECIMAL(14,2) NOT NULL,
    costo_unit DECIMAL(14,4) NULL,
    CONSTRAINT fk_detalle_factura FOREIGN KEY (factura_id) REFERENCES facturas(id) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES productos(id),
    INDEX idx_detalle_factura (factura_id),
    INDEX idx_detalle_producto (producto_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE cobros (
    id INT AUTO_INCREMENT PRIMARY KEY,
    factura_id INT NOT NULL,
    fecha DATE NULL,
    monto DECIMAL(14,2) NOT NULL,
    banco VARCHAR(80) NULL,
    forma_pago VARCHAR(40) NULL,
    observaciones VARCHAR(250) NULL,
    registrado_por VARCHAR(40) NOT NULL,
    CONSTRAINT fk_cobros_factura FOREIGN KEY (factura_id) REFERENCES facturas(id) ON DELETE CASCADE,
    INDEX idx_cobros_fecha (fecha),
    INDEX idx_cobros_factura (factura_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE VIEW v_facturas AS
SELECT *, YEAR(emision) AS anio
FROM facturas;

CREATE VIEW v_facturas_completo AS
SELECT t.*,
       GREATEST(t.total_neto - t.cobrado, 0) AS saldo,
       GREATEST(t.cobrado - t.total_neto, 0) AS excedente,
       CONVERT(CASE
           WHEN t.anulada = 1 THEN 'ANULADA'
           WHEN t.cobrado >= t.total_neto - 0.10 THEN 'COBRADA'
           WHEN t.cobrado > 0 THEN 'PARCIAL'
           WHEN t.vencimiento < CURDATE() THEN 'VENCIDA'
           ELSE 'PENDIENTE'
       END USING utf8mb4) COLLATE utf8mb4_unicode_ci AS estado
FROM (
    SELECT f.*, YEAR(f.emision) AS anio,
           COALESCE(c.razon_social, 'SIN DATOS') AS cliente,
           c.ruc,
           (SELECT COALESCE(SUM(o.monto), 0) FROM cobros o WHERE o.factura_id = f.id) AS cobrado,
           DATEDIFF(f.vencimiento, CURDATE()) AS dias,
           (SELECT o.banco FROM cobros o WHERE o.factura_id = f.id ORDER BY o.id DESC LIMIT 1) AS banco
    FROM facturas f
    LEFT JOIN clientes c ON c.id = f.cliente_id
) AS t;

